#!/usr/bin/env bash
# Starts the answer/boot HTTP server and dnsmasq in proxyDHCP mode.
# The Spectrum router keeps handing out IPs; dnsmasq only adds PXE boot info.
# Ctrl-C stops both.
set -euo pipefail
cd "$(dirname "$0")"
source ./config.env

[ -f out/build.env ] || { echo "Run ./build.sh first." >&2; exit 1; }
source out/build.env
current=$(ipconfig getifaddr "$LAN_IFACE" || true)
if [ "$current" != "$SERVER_IP" ]; then
  echo "Mac IP on $LAN_IFACE is '${current:-none}', but the build used $SERVER_IP. Re-run ./build.sh." >&2
  exit 1
fi

DNSMASQ="$(brew --prefix dnsmasq)/sbin/dnsmasq"
cat > out/dnsmasq.conf <<EOF
# Generated by run.sh
port=0
interface=$LAN_IFACE
bind-interfaces
dhcp-range=${SERVER_IP%.*}.0,proxy,255.255.255.0
log-dhcp
enable-tftp
tftp-root=$PWD/out/tftp
user=$(id -un)
group=$(id -gn)
pxe-service=x86PC,"Proxmox auto-install (BIOS)",undionly.kpxe
pxe-service=x86-64_EFI,"Proxmox auto-install (UEFI)",ipxe.efi
pxe-service=BC_EFI,"Proxmox auto-install (UEFI)",ipxe.efi
EOF
"$DNSMASQ" --test -C out/dnsmasq.conf

python3 server/server.py serve &
server_pid=$!
trap 'kill "$server_pid" 2>/dev/null' EXIT

echo "Starting dnsmasq (proxyDHCP + TFTP) on $LAN_IFACE; sudo needed for ports 67/69/4011."
echo "Mac kept awake (caffeinate) while this runs; keep it plugged in."
caffeinate -i sudo "$DNSMASQ" --keep-in-foreground --log-facility=- -C out/dnsmasq.conf
