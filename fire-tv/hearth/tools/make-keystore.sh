#!/usr/bin/env bash
# Creates the local release-signing keystore for Hearth, outside the repo, if it does not
# already exist. app/build.gradle.kts reads ~/.hearth-keys/KEY-INFO.txt to sign release
# builds. The certificate subject is KEYSTORE_DNAME from config/site.env (default CN=Hearth):
# it ships inside every APK, so keep it to what you'd publish.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../../tools/site.sh"

KEY_DIR="$HOME/.hearth-keys"
KEYSTORE="$KEY_DIR/hearth-release.keystore"
INFO="$KEY_DIR/KEY-INFO.txt"
ALIAS="hearth"

if [[ -f "$INFO" ]]; then
    echo "keystore already set up at $KEYSTORE ($INFO exists)"
    exit 0
fi

mkdir -p "$KEY_DIR"
chmod 700 "$KEY_DIR"

STORE_PASSWORD="$(openssl rand -base64 24 | tr -d '/+=' | cut -c1-24)"
KEY_PASSWORD="$STORE_PASSWORD"

keytool -genkeypair \
    -keystore "$KEYSTORE" \
    -alias "$ALIAS" \
    -keyalg RSA -keysize 2048 -validity 10950 \
    -storepass "$STORE_PASSWORD" -keypass "$KEY_PASSWORD" \
    -dname "${KEYSTORE_DNAME:-CN=Hearth}"

cat > "$INFO" <<EOF
# Hearth release keystore. Keep this file and the .keystore next to it private; neither is
# in version control. Generated by hearth/tools/make-keystore.sh.
storeFile=$KEYSTORE
storePassword=$STORE_PASSWORD
keyAlias=$ALIAS
keyPassword=$KEY_PASSWORD
EOF
chmod 600 "$KEYSTORE" "$INFO"

echo "keystore created at $KEYSTORE"
echo "credentials written to $INFO"
